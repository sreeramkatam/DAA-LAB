INF = float('inf')

n = int(input("Enter number of vertices: "))

print("Enter the adjacency matrix (use INF for infinity):")
dist = []

for i in range(n):
    row = input().split()
    dist.append([INF if x.upper() == "INF" else int(x) for x in row])

# Floyd-Warshall Algorithm
for k in range(n):
    for i in range(n):
        for j in range(n):
            dist[i][j] = min(dist[i][j],
                             dist[i][k] + dist[k][j])

# Display shortest distance matrix
print("\nShortest Distance Matrix:")
for row in dist:
    print(" ".join("INF" if x == INF else str(x) for x in row))

