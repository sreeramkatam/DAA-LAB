class DisjointSet:
    def __init__(self, vertices):
        self.parent = {v: v for v in vertices}
        self.rank = {v: 0 for v in vertices}

    def find(self, item):
        if self.parent[item] == item:
            return item
        self.parent[item] = self.find(self.parent[item])  # Path compression
        return self.parent[item]

    def union(self, set1, set2):
        root1 = self.find(set1)
        root2 = self.find(set2)

        if root1 != root2:
            # Union by rank
            if self.rank[root1] > self.rank[root2]:
                self.parent[root2] = root1
            elif self.rank[root1] < self.rank[root2]:
                self.parent[root1] = root2
            else:
                self.parent[root2] = root1
                self.rank[root1] += 1
            return True
        return False

def kruskal(vertices, edges):
    """
    Computes the Minimum Spanning Tree using Kruskal's algorithm.

    :param vertices: List of vertices
    :param edges: List of tuples (weight, u, v) representing undirected edges
    :return: List of edges included in the MST, and the total cost
    """
    # 1. Sort edges by weight
    sorted_edges = sorted(edges, key=lambda edge: edge[0])

    dsu = DisjointSet(vertices)
    mst = []
    mst_cost = 0

    for weight, u, v in sorted_edges:
        # 2. If u and v are not in the same set, add edge to MST and union sets
        if dsu.union(u, v):
            mst.append((u, v, weight))
            mst_cost += weight
            # Optimization: Stop once we have V - 1 edges
            if len(mst) == len(vertices) - 1:
                break

    return mst, mst_cost

# Example usage of Kruskal's Algorithm
vertices = ['A', 'B', 'C', 'D', 'E', 'F']
# Edges representation: (weight, vertex1, vertex2)
edges = [
    (4, 'A', 'B'),
    (4, 'A', 'C'),
    (2, 'B', 'C'),
    (3, 'C', 'D'),
    (3, 'C', 'E'),
    (1, 'C', 'F'),
    (3, 'D', 'E'),
    (2, 'E', 'F')
]

mst, total_cost = kruskal(vertices, edges)

print("Edges in the Minimum Spanning Tree (MST):")
for u, v, weight in mst:
    print(f"  {u} - {v} (weight: {weight})")
print(f"\nTotal cost of the MST: {total_cost}")